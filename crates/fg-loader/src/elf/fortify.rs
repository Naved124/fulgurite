/// If `name` is a fortified variant (`__memcpy_chk`), the function it protects.
pub(crate) fn fortified_base(name: &str) -> Option<&'static str> {
    let inner = name.strip_prefix("__")?.strip_suffix("_chk")?;
    FORTIFIABLE.iter().copied().find(|f| *f == inner)
}

/// True if `name` has a fortified variant.
pub(crate) fn is_fortifiable(name: &str) -> bool {
    FORTIFIABLE.contains(&name)
}
